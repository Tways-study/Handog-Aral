// Renders the 3D owl once and writes its idle still to src/lib/owl/bundledPoster.ts, the picture shown on a device's very
// first visit (before it has ever drawn the 3D owl itself). Re-run when the 3D model, palette or camera changes, and bump
// POSTER_VERSION in src/lib/owl/poster.ts.
//   npm run build && npx next start -p 3200   (in another shell)
//   PW_CHROMIUM_PATH=/path/to/chrome node scripts/gen-owl-poster.mjs [http://localhost:3200]
import { chromium } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const base = process.argv[2] ?? "http://localhost:3200";
const browser = await chromium.launch({
  executablePath: process.env.PW_CHROMIUM_PATH || undefined,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"],
});
const page = await (await browser.newContext({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 2 })).newPage();
await page.addInitScript(() => {
  localStorage.setItem("handog-owl3d-software", "1"); // the dev switch that lets software GL draw the owl
  localStorage.setItem("handog-mirror:handog-settings", JSON.stringify({ state: { onboarded: true, language: "tagalog", owl3d: true, owlOutfit: "none", theme: "light" }, version: 4 }));
});
await page.route("**/api/**", (r) => r.fulfill({ status: 503, body: "{}" }));
// The scan screen's hero owl is 136px on desktop; the welcome owl is larger. Use the largest idle owl we can reach.
await page.goto(`${base}/welcome`);
const key = "handog-owl-poster:1:idle:none";
const deadline = Date.now() + 40_000;
let poster = null;
while (Date.now() < deadline && !poster) {
  poster = await page.evaluate((k) => localStorage.getItem(k), key);
  await page.waitForTimeout(500);
}
await browser.close();
if (!poster) throw new Error("the 3D owl never rendered (is the build served and WebGL available?)");
const { url, px } = JSON.parse(poster);
const dir = mkdtempSync(join(tmpdir(), "owl-poster-"));
const png = join(dir, "owl.png");
const webp = join(dir, "owl.webp");
writeFileSync(png, Buffer.from(url.split(",")[1], "base64"));
execFileSync("python3", ["-c", `from PIL import Image; Image.open(${JSON.stringify(png)}).convert("RGBA").save(${JSON.stringify(webp)}, "WEBP", quality=88, method=6)`]);
const dataUrl = "data:image/webp;base64," + readFileSync(webp).toString("base64");
writeFileSync(
  new URL("../src/lib/owl/bundledPoster.ts", import.meta.url),
  `// Generated by scripts/gen-owl-poster.mjs. Do not edit. The idle 3D owl, ${px}px, used until a device has captured its own still.\nexport const BUNDLED_POSTER = { url: "${dataUrl}", px: ${px} } as const;\n`,
);
console.log(`wrote bundledPoster.ts (${px}px, ${Math.round(dataUrl.length / 1024)} KB as a data URL)`);
